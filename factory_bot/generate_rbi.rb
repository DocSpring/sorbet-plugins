# frozen_string_literal: true

# Writes the RBI that the factory_bot Sorbet plugin's rewritten calls refer to: a module per factory under
# FactoryBotTypes, with typed create/build/... methods, its traits, and a `Model` type alias.
#
# Run it inside the app, with the factories loaded:
#
#   RAILS_ENV=test bin/rails runner path/to/generate_rbi.rb sorbet/rbi/dsl/factory_bot_types.rbi
#
# Attribute values are T.untyped for now; the keyword names are checked.

output = ARGV.fetch(0) { raise 'usage: generate_rbi.rb <output.rbi>' }

FactoryBot.find_definitions if FactoryBot.factories.none?

RUBY_KEYWORDS = %w[
  BEGIN END alias and begin break case class def defined? do else elsif end ensure false for if in module next nil not
  or redo rescue retry return self super then true undef unless until when while yield __FILE__ __LINE__ __ENCODING__
].freeze

def camelize(name) = name.to_s.split('_').reject(&:empty?).map { |part| part[0].upcase + part[1..] }.join

def factory_chain(factory)
  chain = []
  while factory.is_a?(FactoryBot::Factory)
    chain << factory
    factory = factory.send(:parent)
  end
  chain
end

def traits_for(factory)
  factory_chain(factory).flat_map { |f| f.definition.defined_traits.map { |trait| trait.name.to_s } }.uniq.sort
end

def keyword_names(factory, model)
  names = factory.send(:attributes).names.map(&:to_s)
  model.define_attribute_methods if model.respond_to?(:define_attribute_methods)
  setters = model.public_instance_methods.map(&:to_s).grep(/\A[a-z_][a-zA-Z0-9_]*=\z/).map { |m| m.delete_suffix('=') }
  (names + setters).uniq.reject { |name| RUBY_KEYWORDS.include?(name) }.sort
end

lines = []
lines << '# typed: true'
lines << ''
lines << '# DO NOT EDIT. Generated by sorbet-plugins/factory_bot/generate_rbi.rb for the factory_bot Sorbet plugin.'
lines << ''
lines << 'module FactoryBotTypes'

FactoryBot.factories.sort_by { |f| f.name.to_s }.each do |factory|
  factory.compile
  model = factory.build_class
  module_name = camelize(factory.name)
  keywords = keyword_names(factory, model)
  kw_params = keywords.map { |k| "#{k}: T.untyped" }
  kw_args = keywords.map { |k| "#{k}: T.unsafe(nil)" }
  params = ->(*leading, block) { [*leading, 'traits: Symbol', *kw_params, block].compact.join(', ') }
  args = ->(*leading, block) { [*leading, '*traits', *kw_args, block].compact.join(', ') }

  lines << "  module #{module_name}"
  lines << "    Model = T.type_alias { ::#{model.name} }"
  lines << ''
  %w[create build build_stubbed].each do |method|
    lines << "    sig { params(#{params.call('blk: T.nilable(T.proc.params(arg0: Model).void)')}).returns(Model) }"
    lines << "    def self.#{method}(#{args.call('&blk')}); end"
    lines << ''
  end
  %w[create_list build_list build_stubbed_list].each do |method|
    block = 'blk: T.nilable(T.proc.params(arg0: Model, arg1: Integer).void)'
    lines << "    sig { params(#{params.call('count: Integer', block)}).returns(T::Array[Model]) }"
    lines << "    def self.#{method}(#{args.call('count', '&blk')}); end"
    lines << ''
  end
  %w[create_pair build_pair build_stubbed_pair].each do |method|
    lines << "    sig { params(#{params.call(nil)}).returns(T::Array[Model]) }"
    lines << "    def self.#{method}(#{args.call(nil)}); end"
    lines << ''
  end
  lines << "    sig { params(#{params.call(nil)}).returns(T::Hash[Symbol, T.untyped]) }"
  lines << "    def self.attributes_for(#{args.call(nil)}); end"
  lines << ''
  lines << '    module Traits'
  traits_for(factory).each do |trait|
    lines << '      sig { returns(Symbol) }'
    lines << "      def self.#{trait}; end"
  end
  lines << '    end'
  lines << '  end'
  lines << ''
end
lines.pop if lines.last.empty?
lines << 'end'

File.write(output, "#{lines.join("\n")}\n")
puts "Wrote #{FactoryBot.factories.count} factories to #{output}"
