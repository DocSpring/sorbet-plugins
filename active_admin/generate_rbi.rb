# frozen_string_literal: true

# Writes the RBI that the active_admin Sorbet plugin's rewritten registrations refer to. For each registered resource
# or page, under ActiveAdminTypes::Resources::<Name> or ActiveAdminTypes::Pages::<Name>:
#
# - `Controller`: a stand-in subclass of the real controller. The plugin moves `controller do` bodies and the blocks
#   of member, collection, page and batch actions into it, typed with the resource (`resource` returns the model).
# - `View`: the self type of view blocks (`index`, `show`, `form`, `action_item`, `content`, ...): Arbre's builder
#   methods, ActiveAdmin's components, the controller's view helpers and route helpers, and a typed `resource`.
#
# Run it inside the app, with ActiveAdmin's registrations loaded:
#
#   RAILS_ENV=development bin/rails runner path/to/generate_rbi.rb sorbet/rbi/dsl/active_admin_types.rbi

output = ARGV.fetch(0) { raise 'usage: generate_rbi.rb <output.rbi>' }

ActiveAdmin.application.load!

# Must match `camelize` in ActiveAdmin.cc: split on anything but letters and digits, upcase each part's first letter.
def camelize(name) = name.to_s.split(/[^A-Za-z0-9]+/).reject(&:empty?).map { |part| part[0].upcase + part[1..] }.join

SIMPLE_METHOD = /\A[a-z_][a-zA-Z0-9_]*[?!]?\z/
PROJECT_ROOT = "#{File.expand_path(Rails.root.to_s)}/"
# Gems can live inside the project (vendor/bundle on CI, vendored gems), so a file under the root isn't necessarily
# the app's own.
GEM_DIRS = [*Gem.path, Bundler.bundle_path.to_s, "#{PROJECT_ROOT}vendor"].map { |dir| "#{File.expand_path(dir)}/" }

def app_file?(path)
  path = File.expand_path(path)
  path.start_with?(PROJECT_ROOT) && GEM_DIRS.none? { |dir| path.start_with?(dir) }
end

def stub(name, indent) = "#{indent}def #{name}(*args, **kwargs, &blk); end"

def nameable?(mod) = mod.name && !mod.name.start_with?('#<') && Object.const_get(mod.name).equal?(mod)

def project_method?(mod, name)
  location = mod.instance_method(name).source_location&.first
  location && app_file?(location)
end

# Methods the app defines on a class at runtime (`ResourceController.class_eval do def self.x`): Sorbet can't see
# them, so they're stubbed. Reopening the class instead would make these unnecessary.
def project_methods(klass)
  instance = klass.instance_methods(false).select { |name| project_method?(klass, name) }
  singleton = klass.singleton_class.instance_methods(false).select { |name| project_method?(klass.singleton_class, name) }
  [instance.map(&:to_s).grep(SIMPLE_METHOD).sort, singleton.map(&:to_s).grep(SIMPLE_METHOD).sort]
end

# Methods Arbre elements answer in view blocks: Arbre's and ActiveAdmin's builder methods (`div`, `panel`,
# `attributes_table`), and the DSL of the components whose blocks keep the view's self (`column`, `row`, `actions`,
# `tab`). Block params and return values are untyped.
COMPONENTS = %w[
  ActiveAdmin::Views::IndexAsTable ActiveAdmin::Views::IndexAsTable::IndexTableFor ActiveAdmin::Views::TableFor ActiveAdmin::Views::AttributesTable
  ActiveAdmin::Views::Columns ActiveAdmin::Views::Panel ActiveAdmin::Views::Tabs ActiveAdmin::Views::ActiveAdminForm
  ActiveAdmin::CSVBuilder ActiveAdmin::Views::IndexAsBlog ActiveAdmin::Views::IndexAsGrid ActiveAdmin::Views::SidebarSection
  ActiveAdmin::Views::StatusTag ActiveAdmin::Views::DropdownMenu ActiveAdmin::Views::Pages::Show
  ActiveAdmin::Views::Pages::Index ActiveAdmin::Views::Pages::Form ActiveAdmin::Views::Pages::Page
].filter_map { |name| name.safe_constantize }
view_methods = (Arbre::Element::BuilderMethods.instance_methods +
                COMPONENTS.flat_map { |klass| klass.public_instance_methods }).map(&:to_s).uniq.grep(SIMPLE_METHOD)
view_methods -= (Arbre::Element.public_instance_methods - Arbre::Element::BuilderMethods.instance_methods).map(&:to_s)
view_methods -= %w[method_missing respond_to_missing?]
view_methods.sort!

lines = []
lines << '# typed: true'
lines << ''
lines << '# DO NOT EDIT. Generated by sorbet-plugins/active_admin/generate_rbi.rb for the active_admin Sorbet plugin.'
lines << ''
[ActiveAdmin::BaseController, ActiveAdmin::ResourceController, ActiveAdmin::PageController].each do |klass|
  instance, singleton = project_methods(klass)
  next if instance.empty? && singleton.empty?

  lines << "class #{klass.name} < ::#{klass.superclass.name}"
  instance.each { |name| lines << stub(name, '  ') }
  singleton.each { |name| lines << stub("self.#{name}", '  ') }
  lines << 'end'
  lines << ''
end

lines << 'module ActiveAdminTypes'
lines << '  # The self type of view blocks, without the resource or the controller\'s helpers.'
lines << '  class View < ::Arbre::Element'
lines << '    include ::Arbre::Element::BuilderMethods'
lines << '    include ::ActionView::Helpers'
# What the app's initializers mix into every view (Chartkick's `column_chart`, ERB::Util's `html_escape`).
(ActionView::Base.ancestors.reject { |mod| mod.is_a?(Class) } - ActionView::Helpers.ancestors - Object.ancestors).select { |mod| nameable?(mod) }
  .reverse_each { |mod| lines << "    include ::#{mod.name}" }
view_methods.each { |name| lines << stub(name, '    ') }
lines << '  end'

count = 0
ActiveAdmin.application.namespaces.each do |namespace|
  namespace.resources.each do |resource|
    page = resource.is_a?(ActiveAdmin::Page)
    kind = page ? 'Pages' : 'Resources'
    name = camelize(page ? resource.name : resource.resource_name.name)
    controller = resource.controller
    model = page ? nil : resource.resource_class

    helpers = controller._helpers.ancestors.select { |mod| nameable?(mod) }
    # `helper_method` delegators (`current_user`) live in each controller's HelperMethods module and in anonymous
    # helper modules, which Rails fills in at runtime.
    helper_methods = controller._helpers.ancestors.select { |mod| !nameable?(mod) || mod.name.end_with?('::HelperMethods') }
                               .flat_map { |mod| mod.instance_methods(false) }
    helper_methods = (helper_methods + controller._helper_methods).map(&:to_s).uniq.grep(SIMPLE_METHOD).sort

    lines << ''
    lines << "  module #{kind}::#{name}"
    lines << "    class Controller < ::#{controller.name}"
    if model
      lines << "      sig { returns(::#{model.name}) }"
      lines << '      def resource; end'
    end
    lines << '    end'
    lines << ''
    lines << '    class View < ::ActiveAdminTypes::View'
    helpers.reverse_each { |mod| lines << "      include ::#{mod.name}" }
    lines << '      include ::GeneratedUrlHelpersModule'
    lines << '      include ::GeneratedPathHelpersModule'
    helper_methods.each { |method| lines << stub(method, '      ') unless method == 'resource' }
    if model
      # InheritedResources' instance variables (`@account`, `@accounts`), which Arbre answers by name.
      config = controller.resources_configuration[:self]
      lines << "      sig { returns(::#{model.name}) }"
      lines << '      def resource; end'
      lines << "      sig { returns(::#{model.name}) }"
      lines << "      def #{config[:instance_name]}; end"
      lines << stub(config[:collection_name], '      ')
      # `belongs_to :account` parents, by their instance variable names.
      controller.resources_configuration.except(:self).each_value do |parent|
        next unless parent[:parent_class].is_a?(Class) && SIMPLE_METHOD.match?(parent[:instance_name].to_s)

        lines << "      sig { returns(T.nilable(::#{parent[:parent_class].name})) }"
        lines << "      def #{parent[:instance_name]}; end"
      end
    end
    lines << '    end'
    lines << '  end'
    count += 1
  end
end
lines << 'end'

# The real controllers ActiveAdmin defines at runtime, for the stand-ins to subclass.
ActiveAdmin.application.namespaces.each do |namespace|
  namespace.resources.each do |resource|
    controller = resource.controller
    lines << ''
    lines << "class #{controller.name} < ::#{controller.superclass.name}; end"
  end
end

modules = %w[ActiveAdminTypes::Resources ActiveAdminTypes::Pages]
File.write(output, "#{lines.join("\n")}\n#{modules.map { |mod| "\nmodule #{mod}; end" }.join}\n")
puts "Wrote #{count} resources and pages to #{output}"
