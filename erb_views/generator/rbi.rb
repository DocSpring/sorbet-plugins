# frozen_string_literal: true

require_relative 'code'
require_relative 'names'
require_relative 'partial_locals'
require_relative 'signatures'
require_relative 'template_ruby'
require_relative 'types'

module ErbViews
  # Writes sorbet/rbi/plugins/erb_views.rbi: a context class per template, which the plugin's class for the template
  # inherits. A controller template's context inherits its controller's `HelperProxy` (Tapioca's view class: every
  # helper module, and the `helper_method`s with their sigs), a mailer template's the mailer's helpers, a component
  # template's the component. Each context declares the ivars that reach the template and, for a partial without a
  # locals comment, its locals (with one, they're the template's parameters). A view's context also declares the
  # method each of its literal partial renders calls, with the partial's locals.
  class Rbi
    HEADER = <<~RBI
      # typed: true

      # DO NOT EDIT MANUALLY
      # Generated by the erb_views Sorbet plugin's generator: run `bin/sorbet-plugin-rbis`.
      # Each template's class (SorbetViews::Templates::ShowHtml for app/views/templates/show.html.erb) inherits its
      # context here, which gives it the view's helpers, the instance variables its actions assign and its locals.
    RBI

    # What every template can call besides its controller's helpers.
    VIEW_HELPERS = <<~RBI
      module SorbetViews
        module ViewHelpers
          include ::GeneratedUrlHelpersModule
          include ::GeneratedPathHelpersModule

          sig { returns(T::Hash[Symbol, T.untyped]) }
          def local_assigns; end
        end
      end
    RBI

    # `types` answers `ivar_type(logical, name, ivar)` and `local_type(logical, name)` with a type string.
    def initialize(app, graph, types, helper_proxies:)
      @app = app
      @graph = graph
      @types = types
      @helper_proxies = helper_proxies
      @renderers = app.renderers.to_h { |renderer| [renderer.name, renderer] }
      @sources = {}
      @partial_locals = {}
    end

    def render
      out = +HEADER
      out << "\n" << VIEW_HELPERS
      mailer_contexts.each { |text| out << "\n" << text }
      template_files.each { |file| out << "\n" << context(file) }
      out
    end

    def template_files
      Dir.glob(File.join(@app.root, '{app/views,app/components}/**/*.erb')).sort.map { |file| @app.relative(file) }
    end

    private

    def context(file)
      relative, component = Names.template_path(file)
      parts = Names.class_parts(relative, component)
      logical = logical_name(relative) unless component
      context = logical && @graph.contexts.key?(logical) ? @graph.contexts[logical] : nil
      superclass, extras = component ? [component_superclass(file), []] : view_superclass(context)

      body = extras.dup
      if context
        ivars = ivar_names(context, file).map do |name|
          "    #{name} = T.let(T.unsafe(nil), #{@types.ivar_type(logical, file, name)})"
        end
        body << "  sig { void }\n  def initialize\n#{ivars.join("\n")}\n  end" unless ivars.empty?
        body << "  sig { returns(::User) }\n  def current_user; end" if context.authenticated?
      end
      unless component
        if partial_locals(file).nil?
          locals(context, file).each do |name|
            body << "  sig { returns(#{@types.local_type(logical, name)}) }\n  def #{name}; end"
          end
        end
        body.concat(partial_methods(file, context))
      end
      lines = ["# #{file}"]
      lines << "class ::SorbetViews::Contexts::#{parts.join('::')} < #{superclass}"
      lines << '  include ::SorbetViews::ViewHelpers' unless component
      lines << body.join("\n\n") unless body.empty?
      lines << 'end'
      lines.join("\n") + "\n"
    end

    # The ivars that reach a template, and the ones it assigns itself (for its layout or partials).
    def ivar_names(context, file)
      (context.ivars.keys.reject { |name| name.start_with?('!') } + @graph.template_facts(file).writes.map(&:name)).uniq.sort
    end

    def logical_name(relative)
      dir, base = File.split(relative)
      dir == '.' ? base.split('.').first : "#{dir}/#{base.split('.').first}"
    end

    # The locals a template's callers pass, and the ones it reads through `local_assigns`.
    def locals(context, file)
      passed = context ? context.calls.flat_map { |call| call.locals.keys } : []
      (passed + @graph.template_facts(file).local_keys).uniq.sort.select { |name| name.match?(/\A[a-z_][a-zA-Z0-9_]*\z/) }
    end

    def source(file) = @sources[file] ||= File.read(File.join(@app.root, file))

    def partial_locals(file) = @partial_locals.fetch(file) { @partial_locals[file] = PartialLocals.read(source(file)) }

    # The methods a view's literal partial renders call (`render 'row'` calls `__partial__row`), each with the
    # partial's locals. A name resolves with the prefixes of every renderer that reaches the view, to the partial in
    # the view's format if there is one. One that resolves to partials with different locals, to a partial without a
    # locals comment, or that the generator can't resolve (no renderer is known, or the partial isn't an ERB template
    # in the app) takes any locals. A name that resolves to nothing has no method, so Sorbet reports its render.
    def partial_methods(file, context)
      renderers = context ? context.renderers.map { |name| @renderers.fetch(name) } : []
      names = Code.partial_render_names(Prism.parse(TemplateRuby.call(source(file))).value)
      names.group_by { |name| Names.partial_method(name) }.sort_by(&:first).filter_map do |method, same|
        next if method.nil?

        texts = same.flat_map { |name| partial_texts(name, method, renderers, Rbi.format(file)) }.uniq
        next if texts.empty?

        texts.size == 1 ? texts.first : PartialLocals.untyped_method_rbi(method)
      end
    end

    def partial_texts(name, method, renderers, format)
      prefix_sets = name.include?('/') ? [[]] : renderers.map(&:prefixes).uniq
      return [PartialLocals.untyped_method_rbi(method)] if prefix_sets.empty?

      logicals = prefix_sets.filter_map { |prefixes| @app.resolve(name, prefixes, partial: true) }.uniq
      if logicals.empty?
        return @app.other_partial?(name, prefix_sets) ? [PartialLocals.untyped_method_rbi(method)] : []
      end

      logicals.flat_map do |logical|
        files = @app.files(logical)
        same_format = files.select { |partial| [format, nil].include?(Rbi.format(partial)) }
        (same_format.empty? ? files : same_format).map do |partial|
          locals = partial_locals(partial)
          locals ? locals.method_rbi(method) : PartialLocals.untyped_method_rbi(method)
        end
      end
    end

    # A template's format: `html` for `_row.html.erb`, nil for `_row.erb`.
    def self.format(file)
      parts = File.basename(file).split('.')
      parts.size >= 3 ? parts[-2] : nil
    end

    def component_superclass(file)
      name = @app.components[file]
      name ? "::#{name}" : '::ViewComponent::Base'
    end

    # The view class of the renderers' nearest common ancestor that has a HelperProxy, and what the context adds to
    # it: for mailers, the helper modules and helper_methods every renderer has but the ancestor doesn't.
    def view_superclass(context)
      return ['::ApplicationController::HelperProxy', []] if context.nil? || context.renderers.empty?

      renderers = context.renderers.map { |name| @renderers.fetch(name) }
      classes = renderers.map(&:klass)
      if renderers.all? { |renderer| renderer.kind == :mailer }
        mailer = common_ancestor(classes)
        return ["::SorbetViews::Mailers::#{mailer_context_name(mailer)}", mailer_additions(classes, mailer)]
      end
      common_ancestor(classes).ancestors.grep(Class).each do |klass|
        return ["::#{klass.name}::HelperProxy", []] if klass.name && @helper_proxies.include?(klass.name)
      end
      ['::ActionView::Base', []]
    end

    def mailer_additions(classes, ancestor)
      modules = classes.map { |klass| named_helpers(klass) }.reduce(:&) - named_helpers(ancestor)
      methods = classes.map { |klass| klass._helper_methods.map(&:to_sym) }.reduce(:&) - ancestor._helper_methods.map(&:to_sym)
      modules.reverse.map { |mod| "  include ::#{mod.name}" } + methods.sort.map { |name| Signatures.method_rbi(classes.first, name) }
    end

    # A mailer's helper modules that have RBI. Each class's own `HelperMethods` module (its helper_methods) has none:
    # the contexts declare those methods themselves.
    def named_helpers(klass)
      klass._helpers.ancestors.select do |mod|
        !mod.is_a?(Class) && mod.name && !mod.name.start_with?('#<') && !mod.name.end_with?('::HelperMethods') &&
          Object.const_get(mod.name).equal?(mod)
      rescue NameError
        false
      end
    end

    def common_ancestor(classes)
      classes.map { |klass| klass.ancestors.grep(Class) }.reduce(:&).first
    end

    def mailer_context_name(klass) = klass.name.gsub('::', '')

    # A view class per mailer that renders templates, with the mailer's helper modules.
    def mailer_contexts
      mailers = @graph.contexts.values.flat_map { |context| context.renderers.to_a }.uniq
                      .map { |name| @renderers.fetch(name) }.select { |renderer| renderer.kind == :mailer }
      classes = mailers.flat_map do |renderer|
        renderer.klass.ancestors.grep(Class).take_while { |k| k != ActionMailer::Base } + [ActionMailer::Base]
      end
      classes.uniq.sort_by { |klass| klass.ancestors.size }.map do |klass|
        parent = klass == ActionMailer::Base ? nil : klass.superclass
        helpers = named_helpers(klass) - (parent ? named_helpers(parent) : [])
        includes = helpers.reverse.map { |mod| "  include ::#{mod.name}" }
        methods = klass._helper_methods.map(&:to_sym) - (parent ? parent._helper_methods.map(&:to_sym) : [])
        definitions = methods.sort.map { |name| Signatures.method_rbi(klass, name) }
        superclass = parent ? "::SorbetViews::Mailers::#{mailer_context_name(parent)}" : '::ActionView::Base'
        ["# #{klass.name}'s views", "class ::SorbetViews::Mailers::#{mailer_context_name(klass)} < #{superclass}",
         '  include ::SorbetViews::ViewHelpers', *includes, *definitions, 'end'].join("\n") + "\n"
      end
    end
  end
end
