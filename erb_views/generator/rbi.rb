# frozen_string_literal: true

require 'fileutils'
require 'prism'
require_relative 'code'
require_relative 'ivar_hints'
require_relative 'names'
require_relative 'partial_locals'
require_relative 'template_ruby'
require_relative 'types'

module ErbViews
  # Writes the RBIs for the plugin's template classes, in a directory (sorbet/rbi/erb_views) that mirrors the app:
  #
  # - contexts.rbi: the classes the template classes inherit. A view's class inherits SorbetViews::Contexts::Controller
  #   (ApplicationController's helpers, through its Tapioca HelperProxy) or SorbetViews::Contexts::Mailer
  #   (ApplicationMailer's), by its path, and both include SorbetViews::Partials, the methods literal renders of
  #   partials call. Each ERB partial's own file defines its method; this declares the ones for partials that aren't
  #   ERB templates in the app (a gem's), which take any locals.
  # - app/views/<template>.rbi for each view that needs more than its default context: the helpers of the controllers
  #   or mailers that render it (their nearest common ancestor's, where it adds to ApplicationController's or
  #   ApplicationMailer's), the instance variables it reads or writes with the types they have when they reach it,
  #   `current_user` when every render comes after authentication, and for a template without a locals comment, the
  #   locals its renders pass.
  # - app/components/<template>.rbi: a component template's context, the component's class.
  #
  # So a change to a controller rewrites the RBIs of the templates whose types it changes, and a new view type-checks
  # with its default context before the generator runs.
  class Rbi
    HEADER = <<~RBI
      # typed: true

      # DO NOT EDIT MANUALLY
      # Generated by the erb_views Sorbet plugin's generator: run `bin/sorbet-plugin-rbis`.
    RBI

    CONTEXTS = 'contexts.rbi'

    # `types` answers `ivar_type(logical, file, name)` and `local_type(logical, name)` with a type string.
    # `helper_modules`: the names of the controllers and mailers whose Tapioca RBI declares their own `HelperMethods`.
    def initialize(app, graph, types, helper_modules:)
      @app = app
      @graph = graph
      @types = types
      @helper_modules = helper_modules.to_set
      @renderers = app.renderers.to_h { |renderer| [renderer.name, renderer] }
      @sources = {}
      @trees = {}
      @partial_locals = {}
      @ivar_hints = {}
      unless @helper_modules.include?('ApplicationController')
        raise ArgumentError, "Tapioca's RBI for ApplicationController has no HelperMethods module: run `bin/tapioca dsl`"
      end
    end

    # Path relative to the output directory => text: contexts.rbi, and each template's RBI that has anything in it.
    def files
      found = { CONTEXTS => "#{HEADER}\n#{contexts_body}" }
      template_files.each do |file|
        body = template_body(file)
        found["#{file}.rbi"] = "#{HEADER}\n#{body}" if body
      end
      found
    end

    # All of them in one file, for the type passes' copy of the app. There each template declares every ivar that
    # reaches it, as the passes reveal the ones that pass through it to its partials and layout.
    def combined
      bodies = template_files.filter_map { |file| template_body(file, passing: true) }
      "#{HEADER}\n#{[contexts_body, *bodies].join("\n")}"
    end

    # Writes `files` under `dir`, only the ones whose text changed, and deletes the RBIs there it no longer writes.
    def self.write(dir, files)
      FileUtils.mkdir_p(dir)
      (Dir.glob('**/*.rbi', base: dir) - files.keys).each { |path| File.delete(File.join(dir, path)) }
      files.each do |path, text|
        full = File.join(dir, path)
        next if File.file?(full) && File.read(full) == text

        FileUtils.mkdir_p(File.dirname(full))
        File.write(full, text)
      end
      Dir.glob('**/', base: dir).sort_by { |sub| -sub.size }.each do |sub|
        full = File.join(dir, sub)
        Dir.rmdir(full) if Dir.empty?(full)
      end
    end

    def template_files
      Dir.glob(File.join(@app.root, '{app/views,app/components}/**/*.erb')).sort.map { |file| @app.relative(file) }
    end

    # What the app has to change before the RBIs can be right. The generator writes them anyway, then fails.
    def problems = hint_conflicts + context_problems + render_problems + format_problems

    # The ivars comments that contradict what reaches their templates: a declared type that the values the
    # renderers hand over aren't, nil aside (`@template: Template` where an action assigns a Submission). Declaring
    # an ivar non-nil that an action may leave nil is what a declaration is for.
    def hint_conflicts
      view_files.flat_map do |file|
        relative, = Names.template_path(file)
        ivar_hints(file).filter_map do |name, text|
          declared = SorbetType.parse(text)
          arrival = @types.ivar_arrival(logical_name(relative), name)
          next if declared.nil? || arrival.nil? || arrival == SorbetType::UNTYPED

          assigned = SorbetType.strip_nil(arrival)
          next if assigned == [:name, 'NilClass', nil] || SorbetType.subtype?(assigned, declared)

          "#{file}: #{name} is declared #{text}, but its renderers assign #{SorbetType.render(arrival)}"
        end
      end
    end

    # Views that a kind of renderer (controllers or mailers) renders other than the one their path gives them the
    # helpers of: Sorbet would check them against the wrong helpers.
    def context_problems
      view_files.filter_map do |file|
        relative, = Names.template_path(file)
        mailer = Names.mailer_view?(relative)
        others = renderers(graph_context(logical_name(relative))).reject { |renderer| (renderer.kind == :mailer) == mailer }
        next if others.empty?

        names = others.map(&:name).sort.join(', ')
        if mailer
          "#{file}: #{names} render#{'s' if others.size == 1} it, but its path gives it a mailer's helpers. Move it out of " \
            'the mailer views (a directory named `mailer` or `*_mailer`, or a layout named `*mailer*`)'
        else
          "#{file}: #{names} render#{'s' if others.size == 1} it, but its path gives it a controller's helpers. Move it " \
            'to a mailer\'s directory (one named `*_mailer`, like `application_mailer/`), or name a layout `*mailer*`'
        end
      end
    end

    # Renders of a partial by a name without a `/`, which the plugin finds in the view's own directory, where Rails
    # finds another partial with a renderer's prefixes.
    def render_problems
      view_files.flat_map do |file|
        relative, = Names.template_path(file)
        prefix_sets = renderers(graph_context(logical_name(relative))).map(&:prefixes).uniq
        render_names(file).reject { |name| name.include?('/') }.uniq.filter_map do |name|
          ours = partial_logical(Names.resolve_partial(name, relative))
          theirs = prefix_sets.filter_map { |prefixes| @app.resolve(name, prefixes, partial: true) }.uniq - [ours]
          next if theirs.empty?

          full = theirs.first.sub(%r{/_([^/]+)\z}, '/\1')
          "#{file}: `render '#{name}'` renders app/views/#{theirs.join(' or app/views/')} in Rails, but the plugin reads it " \
            "as app/views/#{ours}: write `render '#{full}'`"
        end
      end
    end

    # Partials whose formats (`_row.html.erb`, `_row.text.erb`) declare different locals: each format's file defines
    # the same method, and Sorbet keeps one.
    def format_problems
      view_files.group_by { |file| Names.partial_name(Names.template_path(file).first) }.filter_map do |name, files|
        next if name.nil? || files.size < 2 || files.map { |file| locals_signature(file) }.uniq.size == 1

        "#{files.join(', ')}: the formats of a partial declare the same locals (their locals and sig comments), as " \
          "every render of `#{name}` calls one method"
      end
    end

    private

    def view_files = template_files.reject { |file| Names.template_path(file)[1] }

    def contexts_body
      partials = other_partial_methods.map { |method| PartialLocals.untyped_method_rbi(method).gsub(/^/, '  ') }
      <<~RBI
        # The classes the plugin's template classes inherit. A view's is its path's: a mailer's view is one under a
        # directory named `mailer` or `*_mailer`, or a layout with `mailer` in its name. Each template's RBI beside this
        # file adds what its renderers give it.
        module SorbetViews
          # What every view can call besides its helpers.
          module ViewHelpers
            include ::GeneratedUrlHelpersModule
            include ::GeneratedPathHelpersModule

            sig { returns(T::Hash[Symbol, T.untyped]) }
            def local_assigns; end
          end

          # The methods that literal renders of partials call (`render 'templates/row'` calls `__partial__templates__row`).
          # Each ERB partial's file defines its own; these are the partials that aren't ERB templates in the app.
          module Partials
        #{partials.join("\n\n")}
          end

          module Contexts
            # A controller's view: ApplicationController's helpers.
            class Controller < ::ApplicationController::HelperProxy
              include ::SorbetViews::ViewHelpers
              include ::SorbetViews::Partials
            end

            # A mailer's view: ApplicationMailer's helpers.
            class Mailer < ::ActionView::Base
              include #{mailer_base_helpers}
              include ::SorbetViews::ViewHelpers
              include ::SorbetViews::Partials
            end
          end
        end
      RBI
    end

    def template_body(file, passing: false)
      relative, component = Names.template_path(file)
      return component_body(file, relative) if component

      logical = logical_name(relative)
      context = graph_context(logical)
      parts = []
      helpers = helpers_module(relative, context)
      parts << "  include #{helpers}" if helpers
      ivars = ivar_types(file, logical, context, passing:).map { |name, type| "    #{name} = T.let(T.unsafe(nil), #{type})" }
      parts << "  sig { void }\n  def initialize\n#{ivars.join("\n")}\n  end" unless ivars.empty?
      parts << "  sig { returns(::User) }\n  def current_user; end" if context&.authenticated?
      if partial_locals(file).nil?
        locals(context, file).each do |name|
          parts << "  sig { returns(#{@types.local_type(logical, name)}) }\n  def #{name}; end"
        end
      end
      return nil if parts.empty?

      "class #{Names.class_name(file)}\n#{parts.join("\n\n")}\nend\n"
    end

    def component_body(file, relative)
      name = @app.components[file]
      "class ::SorbetViews::Contexts::#{Names.class_parts(relative, true).join('::')} < ::#{name || 'ViewComponent::Base'}; end\n"
    end

    # The `HelperMethods` of the renderers' nearest common ancestor that has one, unless it's the default context's:
    # it includes its parents' (sorbet/tapioca/compilers/helper_methods.rb in the app).
    def helpers_module(relative, context)
      classes = renderers(context).map(&:klass)
      return nil if classes.empty?

      owner = classes.map { |klass| klass.ancestors.grep(Class) }.reduce(:&).find { |klass| klass.name && @helper_modules.include?(klass.name) }
      return nil if owner.nil?

      name = "::#{owner.name}::HelperMethods"
      default = Names.mailer_view?(relative) ? mailer_base_helpers : '::ApplicationController::HelperMethods'
      name == default ? nil : name
    end

    # ApplicationMailer's helpers, or with no RBI for them, ActionMailer's.
    def mailer_base_helpers
      @mailer_base_helpers ||= begin
        base = defined?(::ApplicationMailer) ? ::ApplicationMailer : nil
        owner = base&.ancestors&.grep(Class)&.find { |klass| klass.name && @helper_modules.include?(klass.name) }
        owner ? "::#{owner.name}::HelperMethods" : '::ActionMailer::Base::HelperMethods'
      end
    end

    def renderers(context) = context ? context.renderers.map { |name| @renderers.fetch(name) } : []

    def graph_context(logical) = logical && @graph.contexts.key?(logical) ? @graph.contexts[logical] : nil

    # name => type for the ivars a template reads or writes (with `passing`, every one that reaches it): an ivars
    # comment's, or what reaches the template (nil where nothing does but the template assigns it).
    def ivar_types(file, logical, context, passing: false)
      hints = ivar_hints(file)
      reaching = context ? context.ivars.keys.reject { |name| name.start_with?('!') } : []
      reaching &= used_ivars(file) unless passing
      writes = @graph.template_facts(file).writes.map(&:name)
      names = (reaching + writes + hints.keys).uniq.sort
      names.to_h { |name| [name, hints.key?(name) ? Types.qualify(hints[name]) : @types.ivar_type(logical, file, name)] }
    end

    def used_ivars(file) = Code.ivar_names(tree(file)).to_a

    def logical_name(relative)
      dir, base = File.split(relative)
      dir == '.' ? base.split('.').first : "#{dir}/#{base.split('.').first}"
    end

    # `templates/row` => `templates/_row`, the app's name for the partial's files.
    def partial_logical(name)
      dir, base = File.split(name)
      dir == '.' ? "_#{base}" : "#{dir}/_#{base}"
    end

    # The locals a template's callers pass, and the ones it reads through `local_assigns`.
    def locals(context, file)
      passed = context ? context.calls.flat_map { |call| call.locals.keys } : []
      (passed + @graph.template_facts(file).local_keys).uniq.sort.select { |name| name.match?(/\A[a-z_][a-zA-Z0-9_]*\z/) }
    end

    def source(file) = @sources[file] ||= File.read(File.join(@app.root, file))

    def tree(file) = @trees[file] ||= Prism.parse(TemplateRuby.call(source(file))).value

    # The partial names of a view's literal renders (`render 'row'`), as written.
    def render_names(file) = Code.partial_render_names(tree(file))

    # The methods of literal renders, in views, of partials that aren't ERB templates in the app but that Rails finds
    # elsewhere: one with another handler (`_ie9_warning.html`) or in a gem's views (Devise's).
    def other_partial_methods
      view_files.flat_map do |file|
        relative, = Names.template_path(file)
        render_names(file).filter_map do |name|
          resolved = Names.resolve_partial(name, relative)
          method = Names.partial_method(resolved)
          next if method.nil? || !@app.files(partial_logical(resolved)).empty?

          method if @app.other_partial?(resolved, [[Names.view_dir(relative)]])
        end
      end.uniq.sort
    end

    # A view's ivars comment. A component's template has none: its component declares its ivars.
    def ivar_hints(file)
      @ivar_hints.fetch(file) do
        hints = IvarHints.read(source(file), file)
        raise ArgumentError, "#{file}: a component declares its ivars in its class, not in an ivars comment" if hints.any? && Names.template_path(file)[1]

        @ivar_hints[file] = hints
      end
    end

    def partial_locals(file) = @partial_locals.fetch(file) { @partial_locals[file] = PartialLocals.read(source(file)) }

    # What a partial's locals and sig comments declare, to compare its formats.
    def locals_signature(file)
      locals = partial_locals(file)
      locals && [locals.params.map(&:to_a), locals.rest, locals.rest_type]
    end
  end
end
